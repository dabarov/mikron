#!/usr/bin/env node
/**
 * build-site.mjs: builds the project website (landing page with a live demo, and the page shown after an
 * uninstall) into dist/site, which the Pages workflow publishes at https://dabarov.github.io/mikron/.
 *
 *   node tools/build-site.mjs              # -> dist/site
 *   node tools/build-site.mjs --out DIR    # other output folder (used by the tests)
 *
 * The site is static files from site/ plus one generated script, mikron-demo.js: the extension's own content
 * scripts (the files and order of the manifest's content_scripts entry), wrapped in one function together with
 * site/_demo/prelude.js (a stand-in for the extension runtime) and site/_demo/yield.js (steps aside when the real
 * extension is installed). The demo therefore always runs the code that is in extension/. Folders in site/ whose
 * name starts with "_" hold build inputs and are not copied. `__VERSION__` in an HTML file becomes the manifest
 * version. No npm dependencies.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const opt = (k, d) => {
  const i = argv.indexOf(k);
  return i >= 0 ? argv[i + 1] : d;
};
const OUT = path.resolve(opt('--out', path.join(ROOT, 'dist/site')));
const SITE = path.join(ROOT, 'site');
const BASE = '/mikron/'; // where GitHub Pages serves the site
const EXT = path.join(ROOT, 'extension');

function fail(msg) {
  console.error(`build-site: ${msg}`);
  process.exit(1);
}
const read = (f) => fs.readFileSync(f, 'utf8');

const manifest = JSON.parse(read(path.join(EXT, 'manifest.json')));
const scripts = (manifest.content_scripts && manifest.content_scripts[0] && manifest.content_scripts[0].js) || [];
if (!scripts.length) fail('the manifest has no content scripts');
const uiAt = scripts.indexOf('content/ui.js');
const mainAt = scripts.indexOf('content/main.js');
if (uiAt < 0 || mainAt !== scripts.length - 1 || uiAt > mainAt) fail('expected content/ui.js before content/main.js, with main.js last');

// ---- the demo bundle ----------------------------------------------------------------------------
const part = (label, file) => `\n// ---- ${label} ----\n${read(file).trimEnd()}\n`;
const bundle =
  `/* Mikron ${manifest.version} web demo. Generated by tools/build-site.mjs from extension/ and site/_demo/; do not edit.\n` +
  ` * Apache License 2.0, https://github.com/dabarov/mikron */\n` +
  `(function () {\n` +
  part('site/_demo/prelude.js', path.join(SITE, '_demo/prelude.js')) +
  scripts
    .map((s, i) => (i === mainAt ? part('site/_demo/yield.js', path.join(SITE, '_demo/yield.js')) : '') + part(`extension/${s}`, path.join(EXT, s)))
    .join('') +
  `})();\n`;

// ---- copy -----------------------------------------------------------------------------------------
const JUNK = /^(\.DS_Store|Thumbs\.db|desktop\.ini|.*~|.*\.(orig|rej|swp|tmp))$/i;
const written = [];
function write(rel, data) {
  const dst = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, data);
  written.push(rel);
}
function copyTree(dir, rel = '') {
  for (const n of fs.readdirSync(path.join(dir, rel)).sort()) {
    if (JUNK.test(n) || n.startsWith('_')) continue;
    const r = rel ? `${rel}/${n}` : n;
    const st = fs.statSync(path.join(dir, r));
    if (st.isDirectory()) copyTree(dir, r);
    else if (r.endsWith('.html')) write(r, read(path.join(dir, r)).replaceAll('__VERSION__', manifest.version));
    else write(r, fs.readFileSync(path.join(dir, r)));
  }
}

fs.rmSync(OUT, { recursive: true, force: true });
copyTree(SITE);
write('mikron-demo.js', bundle);
write('.nojekyll', '');
// Files that live elsewhere in the repository and are served as they are.
const ASSETS = [
  ['extension/fonts/GeistMono-Bold.woff2', 'fonts/GeistMono-Bold.woff2'],
  ['extension/fonts/OFL.txt', 'fonts/OFL.txt'],
  ['extension/icons/icon32.png', 'img/icon-32.png'],
  ['extension/icons/icon48.png', 'img/icon-48.png'],
  ['extension/icons/icon128.png', 'img/icon-128.png'],
  ['store/assets/hero.gif', 'img/hero.gif'],
  ['store/assets/social-preview-1280x640.png', 'img/social-preview.png'],
];
for (const [from, to] of ASSETS) {
  const src = path.join(ROOT, from);
  if (!fs.existsSync(src)) fail(`missing ${from}`);
  write(to, fs.readFileSync(src));
}

// ---- checks: every local file an HTML page points at exists in the output ------------------------
const errors = [];
for (const f of written.filter((x) => x.endsWith('.html'))) {
  const html = read(path.join(OUT, f));
  if (html.includes('__VERSION__')) errors.push(`${f}: unreplaced __VERSION__`);
  for (const [, url] of html.matchAll(/<(?:script|img|link|a|source|video)\b[^>]*?\b(?:src|href|poster)="([^"]*)"/gi)) {
    if (!url || /^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(url)) continue;
    const clean = url.split(/[?#]/)[0];
    if (!clean) continue;
    // 404.html is served at any depth, so it uses addresses from the site root, which is /mikron/ on Pages
    const rooted = clean.startsWith(BASE) ? clean.slice(BASE.length) || '.' : null;
    if (clean.startsWith('/') && rooted === null) {
      errors.push(`${f} uses an address outside ${BASE}: ${url}`);
      continue;
    }
    const target = rooted !== null ? path.posix.normalize(rooted) : path.posix.normalize(path.posix.join(path.posix.dirname(f), clean));
    const file = target.endsWith('/') || target === '.' ? path.posix.join(target, 'index.html') : target;
    if (!written.includes(file) && !written.includes(path.posix.join(file, 'index.html'))) errors.push(`${f} points at a missing file: ${url}`);
  }
}
if (errors.length) {
  for (const e of errors) console.error(`build-site: ${e}`);
  process.exit(1);
}

let total = 0;
for (const f of written.sort()) {
  const n = fs.statSync(path.join(OUT, f)).size;
  total += n;
  console.log(`${String(n).padStart(8)}  ${f}`);
}
console.log(`\n${written.length} files, ${total} bytes in ${path.relative(process.cwd(), OUT) || OUT}`);
